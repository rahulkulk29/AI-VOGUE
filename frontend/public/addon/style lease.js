// State
let currentCity = '';
let currentCategory = 'all';
let currentSubCategory = 'all';
let maxPrice = 5000;

// DOM Elements
const citySelect = document.getElementById('citySelect');
const searchInput = document.getElementById('searchInput');
const searchBtn = document.getElementById('searchBtn');
const searchBarContainer = document.querySelector('.search-bar');
const productsGrid = document.getElementById('productsGrid');
const filtersContainer = document.getElementById('filtersContainer');
const itemCount = document.getElementById('itemCount');
const priceRange = document.getElementById('priceRange');
const priceValue = document.getElementById('priceValue');

// Initialize
document.addEventListener('DOMContentLoaded', () => {
    // Hide search bar initially
    if (searchBarContainer) searchBarContainer.style.display = 'none';

    // Event Listeners
    if (citySelect) citySelect.addEventListener('change', handleCityChange);
    if (searchBtn) searchBtn.addEventListener('click', performSearch);
    if (searchInput) searchInput.addEventListener('keypress', (e) => {
        if (e.key === 'Enter') performSearch();
    });

    // Price Filter
    if (priceRange) {
        priceRange.addEventListener('input', (e) => {
            maxPrice = parseInt(e.target.value);
            if (priceValue) priceValue.textContent = maxPrice;
            performSearch(); // Re-filter based on price
        });
    }
});

// Handle City Change
function handleCityChange() {
    currentCity = citySelect.value;

    if (currentCity) {
        if (searchBarContainer) searchBarContainer.style.display = 'flex';
        filtersContainer.style.display = 'block';
        searchInput.disabled = false;
        searchBtn.disabled = false;
        // Show empty grid with search prompt
        productsGrid.innerHTML = '';
        itemCount.textContent = `Search for items in ${currentCity}`;
    } else {
        if (searchBarContainer) searchBarContainer.style.display = 'none';
        filtersContainer.style.display = 'none';
        searchInput.disabled = true;
        searchBtn.disabled = true;
        productsGrid.innerHTML = '';
        itemCount.textContent = 'Select a city to view items';
    }
}

// Global Filter Functions (called from HTML)
window.filterCategory = function (category) {
    currentCategory = category;

    // Update active state of buttons
    const buttons = document.querySelectorAll('.category-btn');
    buttons.forEach(btn => {
        if (btn.textContent.toLowerCase() === category) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    // Show/Hide Frocks based on category
    const frocksBtn = document.getElementById('frocksBtn');
    if (category === 'kids') {
        if (frocksBtn) frocksBtn.style.display = 'inline-block';
    } else {
        if (frocksBtn) frocksBtn.style.display = 'none';
        if (currentSubCategory === 'frocks') currentSubCategory = 'all';
    }

    performSearch();
};

window.filterSubCategory = function (subCategory) {
    currentSubCategory = subCategory;

    // Update active state
    const buttons = document.querySelectorAll('.filter-pill');
    buttons.forEach(btn => {
        // Simple check based on text content or onclick attribute
        const onclickAttr = btn.getAttribute('onclick');
        if (onclickAttr && onclickAttr.includes(`'${subCategory}'`)) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    performSearch();
};

// Perform Search
function performSearch() {
    if (!currentCity) {
        alert('Please select a city first');
        return;
    }

    const query = searchInput.value.toLowerCase().trim();

    // Parse Query for Category/SubCategory hints
    let searchCategory = currentCategory;
    let searchSubCategory = currentSubCategory;

    // Simple keyword matching for query
    if (query) {
        if (query.includes('women') || query.includes('woman') || query.includes('ladies')) searchCategory = 'women';
        else if (query.includes('men') || query.includes('man') || query.includes('gent')) searchCategory = 'men';
        else if (query.includes('kid') || query.includes('child') || query.includes('boy') || query.includes('girl')) searchCategory = 'kids';

        if (query.includes('pant') || query.includes('trouser') || query.includes('jeans')) searchSubCategory = 'pants';
        else if (query.includes('shirt') || query.includes('top') || query.includes('blouse')) searchSubCategory = 'shirts';
        else if (query.includes('jacket') || query.includes('coat') || query.includes('blazer')) searchSubCategory = 'jackets';
        else if (query.includes('frock') || query.includes('dress')) searchSubCategory = 'frocks';
        else if (query.includes('t-shirt') || query.includes('tee')) searchSubCategory = 'tshirts';
    }

    // Filter Database
    const filteredItems = thriftDatabase.filter(item => {
        // City Match
        if (item.city !== currentCity) return false;

        // Price Match
        if (item.price > maxPrice) return false;

        // Category Match
        let categoryMatch = true;
        if (query && (query.includes('women') || query.includes('men') || query.includes('kid'))) {
            categoryMatch = item.category === searchCategory;
        } else {
            if (currentCategory !== 'all' && item.category !== currentCategory) categoryMatch = false;
        }

        // SubCategory Match
        let subCategoryMatch = true;
        if (query && (query.includes('pant') || query.includes('shirt') || query.includes('jacket') || query.includes('frock'))) {
            subCategoryMatch = item.subCategory === searchSubCategory;
        } else {
            if (currentSubCategory !== 'all' && item.subCategory !== currentSubCategory) subCategoryMatch = false;
        }

        // Text Search (Name/Description)
        let textMatch = true;
        if (query) {
            const keywords = query.split(' ').filter(k =>
                !['women', 'men', 'kids', 'mens', 'womens', 'pants', 'shirt', 'jacket', 'frock'].includes(k)
            );
            if (keywords.length > 0) {
                const searchString = `${item.name} ${item.description} ${item.brand} ${item.quality}`.toLowerCase();
                textMatch = keywords.every(k => searchString.includes(k));
            }
        }

        return categoryMatch && subCategoryMatch && textMatch;
    });

    renderProducts(filteredItems);
}

// Render Products
